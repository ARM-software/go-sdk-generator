"""Render a YAML or JSON Schema as a Markdown guide."""

import argparse
import json
from pathlib import Path
import re

import jsonschema_markdown
import yaml


def escape_descriptions(value):
    """Keep literal pipes in descriptions from splitting Markdown table cells."""
    if isinstance(value, dict):
        return {
            key: re.sub(r"(?<!\\)\|", r"\\|", item)
            if key == "description" and isinstance(item, str)
            else escape_descriptions(item)
            for key, item in value.items()
        }
    if isinstance(value, list):
        return [escape_descriptions(item) for item in value]
    return value


def generate_guide(source: Path, output: Path, title: str = "") -> None:
    """Generate documentation without changing the source schema or Git index."""
    if source.resolve() == output.resolve():
        raise ValueError("The output must not overwrite the source schema.")

    with source.open(encoding="utf-8") as stream:
        if source.suffix.lower() == ".json":
            schema = json.load(stream)
        elif source.suffix.lower() in (".yaml", ".yml"):
            schema = yaml.safe_load(stream)
        else:
            raise ValueError("The schema must be a .json, .yaml or .yml file.")

    if not isinstance(schema, dict):
        raise ValueError("The schema must be an object, not an empty, scalar or list document.")
    if title:
        schema["title"] = title

    markdown = jsonschema_markdown.generate(escape_descriptions(schema), hide_empty_columns=True)
    header = (
        "<!-- Generated by actions/schema-docs. Do not edit directly; "
        "update the source schema and regenerate. -->\n\n"
    )
    # Render first so a parsing/conversion failure leaves an existing guide intact.
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header + markdown, encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--title", default="")
    args = parser.parse_args()
    generate_guide(args.schema, args.output, args.title)


if __name__ == "__main__":
    main()
